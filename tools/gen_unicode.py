#!/usr/bin/env python3
"""Make src/tm_unitab.h, the character tables GFOpenTransMem finds words
with: which code points are word characters (general category L*, Nd, Mn
or Mc: ICU's u_isalnum plus the marks, as Poedit's tokenizer asks), which
are one-character words (the Ideographic property), and the simple lower
case mapping (ICU's u_tolower). Made from Python's unicodedata; the
Ideographic ranges are PropList.txt's, written out below.
MIT, Copyright (c) 2026 AmiCradle Team.
Run from the top of the tree: python3 tools/gen_unicode.py [--check]"""
import os, sys, unicodedata

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "src/tm_unitab.h")

# PropList.txt, Ideographic=Yes (Unicode 15.1/16.0)
IDEOGRAPHIC = [
    (0x3006, 0x3007), (0x3021, 0x3029), (0x3038, 0x303A), (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF), (0xF900, 0xFA6D), (0xFA70, 0xFAD9), (0x16FE4, 0x16FE4),
    (0x17000, 0x187F7), (0x18800, 0x18CD5), (0x18D00, 0x18D08),
    (0x1B170, 0x1B2FB), (0x20000, 0x2A6DF), (0x2A700, 0x2B739),
    (0x2B740, 0x2B81D), (0x2B820, 0x2CEA1), (0x2CEB0, 0x2EBE0),
    (0x2EBF0, 0x2EE5D), (0x2F800, 0x2FA1D), (0x30000, 0x3134A),
    (0x31350, 0x323AF),
]

WORD = {"Lu", "Ll", "Lt", "Lm", "Lo", "Nd", "Mn", "Mc"}


def ranges(pred):
    out, start = [], None
    for c in range(0x80, 0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def lower(c):
    if c == 0x130:
        return 0x69          # ICU's simple mapping; Python's full one is "i" + U+0307
    s = chr(c).lower()
    return ord(s) if len(s) == 1 else c


def case_runs():
    """(first, last, delta, step): every step-th code point from first to
    last lowers to itself + delta."""
    pairs = [(c, lower(c) - c) for c in range(0x80, 0x110000) if lower(c) != c]
    runs = []
    for c, d in pairs:
        if runs:
            f, l, rd, st = runs[-1]
            if rd == d and (st == 0 and c - l in (1, 2) or st and c - l == st):
                runs[-1] = (f, c, d, st or c - l)
                continue
        runs.append((c, c, d, 0))
    return [(f, l, d, st or 1) for f, l, d, st in runs]


def make():
    word = ranges(lambda c: unicodedata.category(chr(c)) in WORD)
    case = case_runs()
    o = ["/* Generated by tools/gen_unicode.py (Unicode %s): do not edit." % unicodedata.unidata_version,
         " * MIT, Copyright (c) 2026 AmiCradle Team. */",
         "#ifndef TM_UNITAB_H", "#define TM_UNITAB_H", "",
         "/* word characters past 0x7F: L*, Nd, Mn, Mc; first, last */",
         "static const tm_u32 tm_word_ranges[][2] = {"]
    o += ["\t{0x%X, 0x%X}," % r for r in word]
    o += ["};", "", "/* the Ideographic property: first, last */", "static const tm_u32 tm_ideo_ranges[][2] = {"]
    o += ["\t{0x%X, 0x%X}," % r for r in IDEOGRAPHIC]
    o += ["};", "", "/* lower case past 0x7F: first, last, delta, step */",
          "static const struct tm_case_run { tm_u32 first, last; long delta; tm_u32 step; } tm_case_runs[] = {"]
    o += ["\t{0x%X, 0x%X, %d, %d}," % r for r in case]
    o += ["};", "", "#endif", ""]
    return "\n".join(o)


def main():
    text = make()
    if "--check" in sys.argv:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have.split("\n", 1)[0] != text.split("\n", 1)[0]:
            print("gen_unicode: Python has another Unicode version; not checked")
            return
        if have != text:
            sys.exit("src/tm_unitab.h is out of date: run tools/gen_unicode.py")
        print("gen_unicode: src/tm_unitab.h up to date")
        return
    open(OUT, "w").write(text)
    print("wrote", OUT)


main()
